import pandas as pd
# Load dataset into a DataFrame
df = pd.read_csv('marks1.csv')
# Display first and last few rows
print("First 5 rows:\n", df.head())
print("Last 5 rows:\n", df.tail())
# Check data types and general info
df.info()
# Summary statistics
print("Summary statistics:\n", df.describe())

# Handle missing values - fill numeric columns with their mean
numeric_cols = df.select_dtypes(include=['number']).columns
df[numeric_cols] = df[numeric_cols].fillna(df[numeric_cols].mean())

# Filter rows based on conditions using existing columns
filtered_df = df[(df['Maths'] > 75) & (df['English'] < 90)]
print("Filtered DataFrame:\n", filtered_df)

# Sorting by an existing numeric column
df_sorted = df.sort_values(by='Maths', ascending=False)
print("Sorted DataFrame:\n", df_sorted)

# Boolean masking using an existing numeric column
masked_df = df[df['Science'] > df['Science'].median()]
print("Masked DataFrame:\n", masked_df)

# Remove duplicates (if any) and drop rows with any missing values (after filling numeric)
df.drop_duplicates(inplace=True)
df.dropna(inplace=True)

# Create a new DataFrame with selected existing columns
subset_df = df[['Name', 'Maths', 'Science']]
# Save the new DataFrame to a CSV file
subset_df.to_csv('filtered_data.csv', index=False)

# Compute summary statistics for an existing numeric column
print("Total sum of Maths scores:", df['Maths'].sum())
print("Mean of Maths scores:", df['Maths'].mean())
print("Standard Deviation of Maths scores:", df['Maths'].std())

